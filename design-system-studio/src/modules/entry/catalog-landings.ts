interface Def {
  id: string
  name: string
  segment: string
  architecture: LandingArchitecture
  description: string
  summary: string
  sections: string[]
  demo: DemoColors
  headingFont: string
  bodyFont?: string
  radius: number
  content: LandingContent
  structure: string[]
  responsive: string[]
  behavior?: string[]
  measurements?: Record<string, string>
  notes?: string[]
  tags?: string[]
}

function landing(d: Def): LandingModel {
  const arch = ARCH_SPEC[d.architecture]
  const c = d.content
  const header = `Header: logotipo “${c.logo}”, navegação com ${c.nav.map((n) => `“${n}”`).join(', ')}${
    c.login ? ', ação “Entrar” (leva ao login) e' : ' e'
  } CTA “${c.cta}”.`
  const spec: ItemSpec = {
    summary: d.summary,
    structure: [`Ordem das seções: ${d.sections.join(' → ')}.`, header, ...d.structure, ...arch.structure],
    behavior: [...arch.behavior, ...(d.behavior ?? [])],
    responsive: [...d.responsive, ...arch.responsive],
    measurements: { ...arch.measurements, ...(d.measurements ?? {}) },
    notes: [
      `Demonstração original: fundo ${d.demo.bg}, texto ${d.demo.text}, primária ${d.demo.primary}, destaque ${d.demo.accent}; títulos em ${fontName(d.headingFont)}. Por padrão a landing herda a paleta global do projeto.`,
      'Marca, textos e números são fictícios: substitua pelo conteúdo real mantendo a hierarquia e a composição.',
      'Ilustrações da demonstração são placeholders vetoriais; use imagens reais otimizadas com texto alternativo.',
      ...(d.notes ?? []),
    ],
  }
  return {
    id: d.id,
    name: d.name,
    description: d.description,
    tags: [d.segment, architectureName(d.architecture), ...(d.tags ?? [])],
    segment: d.segment,
    architecture: d.architecture,
    sections: d.sections,
    demo: d.demo,
    headingFont: d.headingFont,
    bodyFont: d.bodyFont,
    radius: d.radius,
    content: c,
    spec,
  }
}

