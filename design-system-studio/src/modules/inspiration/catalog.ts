const REFERENCE_NOTE = 'Referência de identidade e composição: não copiar marcas, logotipos, textos ou imagens de terceiros — criar conteúdo original para o projeto.'

type SiteInput = Omit<InspirationSite, 'palettes' | 'name'> & { palettes: string[] }

function site(input: SiteInput): InspirationSite {
  return {
    ...input,
    name: input.brand,
    palettes: buildPalettes(input.palettes),
    spec: { ...input.spec, notes: [...(input.spec.notes ?? []), REFERENCE_NOTE] },
  }
}

