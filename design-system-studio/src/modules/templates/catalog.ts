export const categoryName = (id: string) => TEMPLATE_CATEGORIES.find((c) => c.id === id)?.name ?? id

type TemplateDef = Omit<TemplateModel, 'spec'> & {
  spec: Parameters<typeof buildSpec>[1]
}

function tpl(def: TemplateDef): TemplateModel {
  return { ...def, spec: buildSpec(def.sections, def.spec, def.layout ?? 'stack') }
}

/* ----------------------------- auxiliares de dados ----------------------------- */

function nav(links: string[], cta?: string, extra: Partial<TemplateSection> = {}): TemplateSection {
  return {
    id: 'cabecalho',
    name: 'Cabeçalho',
    description: 'Logo, links principais e a ação de destaque.',
    kind: 'nav',
    variant: 'split',
    links,
    cta,
    ...extra,
  }
}

const col = (title: string, list: string[]): SectionItem => ({ title, list })

function footer(variant: 'columns' | 'simple' | 'big', text: string, items: SectionItem[] = [], extra: Partial<TemplateSection> = {}): TemplateSection {
  return {
    id: 'rodape',
    name: 'Rodapé',
    description: variant === 'simple' ? 'Linha final com logo, links e direitos.' : 'Colunas de links, contato e informações legais.',
    kind: 'footer',
    variant,
    text,
    items,
    links: ['Privacidade', 'Termos de uso'],
    ...extra,
  }
}

const faqItems = (pairs: [string, string][]): SectionItem[] => pairs.map(([title, text]) => ({ title, text }))

