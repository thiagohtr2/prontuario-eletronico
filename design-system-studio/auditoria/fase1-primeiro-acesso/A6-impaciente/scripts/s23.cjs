const L=require('./lib.cjs');
(async()=>{
  const {ctx,page}=await L.open();
  await ctx.grantPermissions(['clipboard-read','clipboard-write'],{origin:'http://127.0.0.1:4300'});
  await page.goto('http://127.0.0.1:4300/#/guiado/objetivo',{waitUntil:'networkidle'});
  let t=Date.now();
  await page.locator('header').getByRole('button',{name:'Master Prompt'}).click();
  await page.waitForTimeout(500); await page.waitForLoadState('networkidle');
  const tNav=Date.now()-t;
  await L.snap(page,'23-prompt-final');
  const stats = await page.evaluate(()=>{const m=document.querySelector('main').innerText; return m.slice(m.indexOf('itens no Master')-4, m.indexOf('Master Prompt\nItens'))});
  console.log({tNav,url:page.url(),stats});
  t=Date.now();
  await page.getByRole('button',{name:'Copiar Master Prompt'}).click();
  await page.waitForTimeout(500);
  const tCopy=Date.now()-t;
  await L.snap(page,'23b-copiado');
  const toasts = await page.evaluate(()=>[...document.querySelectorAll('[role=status],[role=alert],[aria-live]')].map(e=>e.innerText).filter(Boolean));
  const btn = await page.evaluate(()=>[...document.querySelectorAll('main button')].filter(b=>/Copi/.test(b.innerText)).map(b=>b.innerText));
  const clip = await page.evaluate(()=>navigator.clipboard.readText().catch(e=>'ERR '+e.message));
  console.log({tCopy,toasts,btn,clipLen:clip.length, clipHead: clip.slice(0,200)});
  L.fs.writeFileSync(L.path.join(L.BASE,'exportados','02-master-prompt-copiado.md'), clip);
  t=Date.now();
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button',{name:'Baixar .md'}).click()]);
  const fn = dl.suggestedFilename();
  await dl.saveAs(L.path.join(L.BASE,'exportados',fn));
  const tDl=Date.now()-t;
  console.log({tDl,fn});
  console.log('LOGS',page._logs);
  await ctx.close();
})();
