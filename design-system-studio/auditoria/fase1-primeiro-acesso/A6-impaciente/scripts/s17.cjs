const L=require('./lib.cjs');
(async()=>{
  const {ctx,page}=await L.open();
  await page.goto('http://127.0.0.1:4300/#/guiado/revisao',{waitUntil:'networkidle'});
  let t=Date.now();
  await page.getByRole('button',{name:/Aprovar esqueleto e continuar/}).click();
  await page.waitForTimeout(600); await page.waitForLoadState('networkidle');
  const tClick=Date.now()-t;
  await L.snap(page,'17-apos-aprovar');
  await L.snap(page,'17-apos-aprovar-full',true);
  const top = await page.evaluate(()=>document.querySelector('header')?.innerText.replace(/\n/g,' | '));
  const dialogs = await page.evaluate(()=>[...document.querySelectorAll('[role=dialog],[role=alertdialog]')].map(d=>d.innerText.slice(0,800)));
  const i=await L.info(page);
  console.log(JSON.stringify({tClick,url:i.url,h:i.h,top,dialogs}));
  const tx=i.text; const k=Math.max(0,tx.indexOf('Etapa '));
  console.log('---TEXT---\n'+tx.slice(k, k+4000));
  console.log('---CTRLS---\n'+i.ctrls.filter(c=>!/^BUTTON "\d+\./.test(c)).slice(0,40).join('\n'));
  console.log('LOGS',page._logs);
  await ctx.close();
})();
