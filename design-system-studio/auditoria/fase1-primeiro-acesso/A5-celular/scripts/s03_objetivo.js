const L = require('./lib');
const sy = p => p.evaluate(() => Math.round(scrollY));
(async () => {
  const { ctx, page } = await L.open('perfil', 'android');
  await page.goto('http://127.0.0.1:4300/#/guiado/objetivo', { waitUntil: 'networkidle' });
  await page.waitForTimeout(500);
  L.log('A04 rolar até ver os cards (wheel 300)');
  await page.mouse.move(180, 400); await page.mouse.wheel(0, 300); await page.waitForTimeout(500);
  const before = await sy(page);
  L.log('A05 tocar card "Aplicativo ou SaaS"');
  await page.getByRole('button', { name: /Aplicativo ou SaaS/ }).tap();
  await page.waitForTimeout(800);
  console.log('scroll antes', before, 'depois', await sy(page));
  await L.shot(page, '04-objetivo-app-selecionado');
  const pressed = await page.getByRole('button', { name: /Aplicativo ou SaaS/ }).evaluate(e => ({ ap: e.getAttribute('aria-pressed'), cls: e.className }));
  console.log('estado card', JSON.stringify(pressed));
  console.log('footer', JSON.stringify(await L.fixedBars(page)));
  // name field
  L.log('A06 rolar até "Sobre o projeto" e tocar "Nome do projeto"');
  const nome = page.getByPlaceholder('Ex.: Agenda Viva');
  await page.mouse.wheel(0, 900); await page.waitForTimeout(500);
  await nome.tap(); await page.waitForTimeout(400);
  const r = await nome.evaluate(e => { const r = e.getBoundingClientRect(); const f = document.querySelector('.gd-footer').getBoundingClientRect(); return { inputTop: Math.round(r.top), inputBottom: Math.round(r.bottom), footerTop: Math.round(f.top), focused: document.activeElement === e, fs: getComputedStyle(e).fontSize }; });
  console.log('NOME FOCO', JSON.stringify(r));
  L.log('A07 digitar nome');
  await page.keyboard.type('Barbearia da Joana', { delay: 20 });
  L.log('A08 tocar e digitar objetivo');
  await page.getByPlaceholder(/organizar agendamentos/).tap();
  await page.keyboard.type('Clientes marcam corte e barba pelo celular', { delay: 10 });
  L.log('A09 tocar e digitar público');
  await page.getByPlaceholder(/donos de pequenos/).tap();
  await page.keyboard.type('Clientes da barbearia e eu (dona)', { delay: 10 });
  const r2 = await page.getByPlaceholder(/donos de pequenos/).evaluate(e => { const r = e.getBoundingClientRect(); const f = document.querySelector('.gd-footer').getBoundingClientRect(); return { inputTop: Math.round(r.top), inputBottom: Math.round(r.bottom), footerTop: Math.round(f.top) }; });
  console.log('PUBLICO FOCO', JSON.stringify(r2));
  await L.shot(page, '05-objetivo-campos-preenchidos');
  // keyboard approximation: shrink viewport by ~ 320px
  await page.setViewportSize({ width: 360, height: 480 });
  await page.waitForTimeout(400);
  await page.getByPlaceholder(/marcar um horário/).focus();
  await page.waitForTimeout(400);
  const r3 = await page.getByPlaceholder(/marcar um horário/).evaluate(e => { const r = e.getBoundingClientRect(); const f = document.querySelector('.gd-footer').getBoundingClientRect(); return { inputTop: Math.round(r.top), inputBottom: Math.round(r.bottom), footerTop: Math.round(f.top), footerH: Math.round(f.height), vh: innerHeight }; });
  console.log('TECLADO SIMULADO (vh 480) FINALIDADE', JSON.stringify(r3));
  await L.shot(page, '06-objetivo-teclado-simulado-480');
  await page.setViewportSize({ width: 360, height: 800 });
  await page.waitForTimeout(300);
  const btn = page.getByRole('button', { name: /Continuar: Entrada/ });
  console.log('continuar disabled?', await btn.isDisabled(), 'footer text', await page.locator('.gd-footer').innerText());
  await ctx.close();
})();
