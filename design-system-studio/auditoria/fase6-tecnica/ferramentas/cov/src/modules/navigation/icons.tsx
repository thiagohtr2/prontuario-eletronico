/** Ícone de navegação. `filled` aplica preenchimento suave (estilo de ícone “filled/duotone” do tema). */
export function NavIconView({ name, size = 18, strokeWidth = 1.8, filled }: { name: NavIcon; size?: number; strokeWidth?: number; filled?: boolean }) {
  const Icon = ICONS[name] ?? LayoutGrid
  return <Icon size={size} strokeWidth={strokeWidth} aria-hidden="true" fill={filled ? 'currentColor' : 'none'} fillOpacity={filled ? 0.16 : undefined} />
}
