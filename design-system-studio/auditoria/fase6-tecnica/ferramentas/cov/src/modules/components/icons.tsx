const BY_NAME: Record<string, IconEntry> = Object.fromEntries(ICON_LIBRARY.map((e) => [e.name, e]))
/** Aliases de nomes antigos do lucide. */
BY_NAME.AlertTriangle = BY_NAME.TriangleAlert

export function iconByName(name: string | undefined | null): LucideIcon {
  return (name && BY_NAME[name]?.Icon) || Sparkles
}

export function iconLabel(name: string): string {
  return BY_NAME[name]?.label ?? name
}

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()

export function searchIcons(query: string): IconEntry[] {
  const q = norm(query.trim())
  if (!q) return ICON_LIBRARY
  return ICON_LIBRARY.filter((e) => norm(`${e.name} ${e.label} ${e.tags}`).includes(q))
}
