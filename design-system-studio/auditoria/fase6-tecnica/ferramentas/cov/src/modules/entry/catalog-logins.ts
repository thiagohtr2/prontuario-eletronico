const SECURITY_NOTE =
  'Esta tela é uma demonstração de interface. A autenticação real deve ser implementada pela IA com backend seguro: senhas com hash (Argon2id ou bcrypt), limitação de tentativas, sessão em cookie httpOnly + Secure + SameSite, proteção CSRF e HTTPS obrigatório.'

interface Def {
  id: LoginLayout
  name: string
  group: LoginGroup
  composition: string
  description: string
  headline: string
  subline: string
  summary: string
  structure: string[]
  responsive: string[]
  behavior?: string[]
  measurements?: Record<string, string>
  notes?: string[]
}

function login(d: Def): LoginModel {
  const spec: ItemSpec = {
    summary: d.summary,
    structure: [...d.structure, `Textos da demonstração: título “${d.headline}”, subtítulo “${d.subline}”.`],
    behavior: [...(d.behavior ?? []), ...COMMON_BEHAVIOR],
    responsive: [...d.responsive, ...COMMON_RESPONSIVE],
    measurements: { larguraFormulario: '≈360–400 px', alturaInputs: '≈44 px (desktop) / 48 px (celular)', ...(d.measurements ?? {}) },
    notes: [...(d.notes ?? []), SECURITY_NOTE, 'Cores, fontes, cantos e superfícies vêm da identidade global do projeto (tokens).'],
  }
  return {
    id: d.id,
    layout: d.id,
    name: d.name,
    group: d.group,
    composition: d.composition,
    description: d.description,
    headline: d.headline,
    subline: d.subline,
    tags: [d.composition],
    spec,
  }
}

