const { run } = require('./lib');
run(async ({ page, shot, CAP }) => {
  await page.goto('http://127.0.0.1:4300/#/guiado/componentes', { waitUntil: 'networkidle' });
  await page.waitForTimeout(500);
  const reg = page.getByRole('region', { name: /^No projeto/ });
  console.log((await reg.innerText()).replace(/\n+/g, ' | '));
  const it = reg.getByRole('listitem').filter({ hasText: 'Layouts mobile' }).first();
  await it.getByRole('button', { name: 'Personalizar' }).click();
  await page.waitForTimeout(700);
  const dlg = page.getByRole('dialog').first();
  await dlg.getByRole('textbox', { name: 'Nome no projeto' }).fill('Menu inferior flutuante arredondado (dock)');
  await dlg.getByRole('textbox', { name: 'Título da tela', exact: true }).fill('Início');
  await dlg.getByRole('textbox', { name: 'Itens da navegação (um por linha)', exact: true }).fill('Início\nExplorar\nSalvos\nPerfil');
  await dlg.getByRole('group', { name: 'Navegação' }).getByRole('button', { name: 'Dock flutuante' }).click();
  await page.waitForTimeout(300);
  const fab = dlg.getByRole('switch').first();
  console.log('FAB antes:', await fab.getAttribute('aria-checked'), await fab.isChecked().catch(() => '?'));
  await fab.click();
  await page.waitForTimeout(400);
  console.log('FAB depois:', await fab.isChecked().catch(() => '?'));
  await shot('09-componente-menu-inferior-dock-editor', { dir: CAP });
  const s = await dlg.ariaSnapshot();
  console.log(s.slice(s.indexOf('Configuração da instância'), s.indexOf('Exceção individual')));
  await dlg.getByRole('button', { name: 'Concluir' }).click();
  await page.waitForTimeout(500);
  await reg.scrollIntoViewIfNeeded();
  await shot('09-componentes-no-projeto', { dir: CAP, el: reg });
  console.log((await reg.innerText()).replace(/\n+/g, ' | '));
});
